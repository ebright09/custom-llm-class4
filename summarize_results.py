"""Build results/eval_comparison.md from the saved eval summaries (no model is run).

    python summarize_results.py
"""
import json
from pathlib import Path

RUNS = {"Starter corpus": "llm_runs/20260922T224924_640441Z",
        "Expanded corpus v1": "llm_runs/20260922T225202_918677Z",
        "Expanded corpus (final, v2)": "llm_runs/20260922T225358_991487Z"}
STAGES = ["untrained", "final"]


def load(run, stage, name):
    return json.loads((Path(run) / "language_evals" / stage / name).read_text())


def pct(x):
    return "n/a" if x is None else f"{100 * x:.1f}%"


out = ["# Language-eval comparison", "",
       "Generated by `summarize_results.py` from each run's `eval_summary.json` and `eval_results.json`.",
       "", "## Overall", "",
       "| Experiment | Stage | Correct / 48 | Scorable / 48 | Accuracy among scorable | Coverage |",
       "|---|---|---|---|---|---|"]
for label, run in RUNS.items():
    for stage in STAGES:
        o = load(run, stage, "eval_summary.json")["overall"]
        out.append(f"| {label} | {stage} | {o['correct']} | {o['scorable']} | "
                   f"{pct(o['accuracy_scorable_cases'])} | {pct(o['coverage'])} |")

categories = sorted(load(RUNS["Starter corpus"], "final", "eval_summary.json")["by_category"])
out += ["", "## By category (correct / scorable / total)", "",
        "| Category | " + " | ".join(f"{l} {s}" for l in RUNS for s in STAGES) + " |",
        "|---|" + "---|" * (len(RUNS) * len(STAGES))]
for cat in categories:
    cells = []
    for run in RUNS.values():
        for stage in STAGES:
            c = load(run, stage, "eval_summary.json")["by_category"][cat]
            cells.append(f"{c['correct']}/{c['scorable']}/{c['total']}")
    out.append(f"| {cat} | " + " | ".join(cells) + " |")

out += ["", "## Every case after training", "",
        "`1` correct, `0` scored wrong, `u` unscorable (unknown prompt or choice word). "
        "Continuation = the free text the trained model generated after the prompt (temperature 0.8).", "",
        "| Case | Category | Prompt | Answer | Starter | Exp. v1 | Exp. v2 | Exp. v2 pick | Exp. v2 continuation |",
        "|---|---|---|---|---|---|---|---|---|"]
finals = {label: {r["id"]: r for r in load(run, "final", "eval_results.json")} for label, run in RUNS.items()}
mark = lambda r: "1" if r["score"] else ("0" if r["status"] == "scored" else "u")
for cid, r in finals["Expanded corpus (final, v2)"].items():
    s, v1 = finals["Starter corpus"][cid], finals["Expanded corpus v1"][cid]
    out.append(f"| {cid} | {r['category']} | {r['prompt']} | {r['expected']} | {mark(s)} | {mark(v1)} | "
               f"{mark(r)} | {r['predicted_choice'] or '—'} | {r['generated_text'] or '[empty]'} |")
Path("results").mkdir(exist_ok=True)
Path("results/eval_comparison.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out[:14]))
